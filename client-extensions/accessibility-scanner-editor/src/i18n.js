function languageId() {
	try {
		return window.Liferay.ThemeDisplay.getLanguageId();
	}
	catch {
		return document.documentElement.lang || 'en';
	}
}

export function t(key, ...args) {
	const lang = languageId().split(/[-_]/)[0];
	const table = STRINGS[lang] || STRINGS.en;
	let value = table[key] ?? STRINGS.en[key] ?? key;
	args.forEach((arg, i) => {
		value = value.replace(`{${i}}`, String(arg));
	});
	return value;
}

export function isSpanish() {
	return languageId().startsWith('es');
}
